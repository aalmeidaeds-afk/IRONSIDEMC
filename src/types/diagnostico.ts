  data?: string; // Data da ocorrência (ex: "22/10/2026")
  hora?: string; // Hora da ocorrência (ex: "00:05:10")
  dataHora: string; // Data e hora exata combinada (ex: "22/10/2026 00:05:10")
  timestamp: number;
  modulo: string; // Módulo testado ou afetado (ex: "Módulo 12 - Configurações & Governança")
  recurso: string; // Recurso ou funcionalidade específica
